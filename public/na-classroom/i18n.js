function lookup(dict, key) {
  return key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
}

function detectLang() {
  try {
    const q = new URLSearchParams(location.hash.includes('?') ? location.hash.split('?')[1] : location.search);
    const fromQ = (q.get('lang') || '').toLowerCase();
    if (fromQ === 'fr' || fromQ === 'en') return fromQ;
    const stored = (localStorage.getItem(STORAGE) || '').toLowerCase();
    if (stored === 'fr' || stored === 'en') return stored;
  } catch {}
  return 'en';
}

let current = detectLang();

export function getLang() { return current; }

export function setLang(next) {
  const lang = next === 'fr' ? 'fr' : 'en';
  if (lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  try { localStorage.setItem(STORAGE, lang); } catch {}
  window.dispatchEvent(new CustomEvent('na:lang', { detail: { lang } }));
}

export function t(key, vars = {}) {
  const raw = lookup(COPY[current], key);
  const val = raw === undefined ? lookup(COPY.en, key) : raw;
  if (val == null) return key;
  if (typeof val !== 'string') return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function label(en) {
  const key = `labels.${en}`;
  const raw = lookup(COPY[current], key);
  const val = raw === undefined ? lookup(COPY.en, key) : raw;
  return typeof val === 'string' ? val : en;
}

export function initLang() {
  current = detectLang();
  document.documentElement.lang = current;
  window.addEventListener('message', (event) => {
    const data = event.data;
    if (!data || data.type !== 'na-studio-lang') return;
    setLang(data.lang === 'fr' ? 'fr' : 'en');
  });
}
